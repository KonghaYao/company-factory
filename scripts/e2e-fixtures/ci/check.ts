/**
 * Host-controlled CI/Review fixture for the Company Factory live E2E.
 *
 * This file is NOT part of the Agent project. It is copied into a fresh,
 * secret-free sandbox together with a clean export of the accepted commit and a
 * host-generated manifest. It never reads the E2E root, user data, environment
 * variables, the network, or the Agent worktree.
 *
 * The fixture performs deterministic checks:
 * - the exported tree is byte-for-byte the accepted commit (git blob id, sha256,
 *   size, executable mode, no extra/missing/symlinked files);
 * - no test artifacts or credential-shaped filenames were committed;
 * - `git diff --check`-equivalent whitespace/conflict-marker checks;
 * - the delivered `src/e2e.ts` transpiles as TypeScript and declares an export
 *   (transpilation does not execute the delivered code).
 *
 * It prints exactly one canonical JSON line. The orchestrator hashes those bytes
 * and requires the reviewing Agent to report the same digest.
 *
 * Usage: bun check.ts <ci|review> <subject-dir> <manifest.json> <challenge>
 *
 * <challenge> is generated by the orchestrator for this run. It is part of the
 * canonical report, so the digest is bound to this run and cannot be replayed,
 * and the Reviewer's real Bash tool record must contain the same challenge.
 */
import { createHash } from "node:crypto";
import { lstatSync, readFileSync, readdirSync } from "node:fs";
import { basename, join, relative, sep } from "node:path";

type CiMode = "ci" | "review";

type TreeEntry = {
  path: string;
  mode: "100644" | "100755";
  blob: string;
  sha256: string;
  size: number;
};

type Manifest = {
  version: 1;
  commit: string;
  parent?: string | null;
  entries: TreeEntry[];
  parentEntries?: TreeEntry[];
  treeSha256: string;
};

type Report = {
  version: 1;
  mode: CiMode;
  challenge: string;
  commit: string;
  treeSha256: string;
  files: number;
  bytes: number;
  checks: {
    manifestMatched: true;
    fileModesMatched: true;
    srcEntryPresent: true;
    typescriptSyntaxValid: true;
    deliveryExportPresent: true;
    whitespaceClean: true;
    conflictMarkersAbsent: true;
    forbiddenPathsAbsent: true;
    previewArtifactsAbsent: true;
  };
  review?: {
    changedFiles: Array<{ path: string; status: "added" | "modified" | "removed"; size: number }>;
    added: number;
    modified: number;
    removed: number;
  };
};

const MAX_FILES = 2000;
const MAX_FILE_BYTES = 8 * 1024 * 1024;
const MAX_TOTAL_BYTES = 64 * 1024 * 1024;
const MAX_TEXT_BYTES = 1024 * 1024;
const MAX_DEPTH = 64;

class FixtureError extends Error {
  constructor(
    readonly code: string,
    readonly detail?: string,
  ) {
    super(code);
  }
}

function fail(code: string, detail?: string): never {
  throw new FixtureError(code, detail);
}

function safeDetail(value: string): string {
  return value.replace(/[\0-\x1f\x7f]/g, "?").slice(0, 200);
}

function sha256Hex(value: Buffer | string): string {
  return createHash("sha256").update(value).digest("hex");
}

function gitBlobId(value: Buffer): string {
  return createHash("sha1")
    .update(`blob ${value.length}\0`)
    .update(value)
    .digest("hex");
}

function assertSafePath(path: string, label: string): void {
  if (
    !path ||
    path.startsWith("/") ||
    path.includes("\\") ||
    /[\x00-\x1f\x7f]/.test(path)
  )
    fail(`${label}_path_invalid`, path);
  const segments = path.split("/");
  if (segments.some((segment) => !segment || segment === "." || segment === ".."))
    fail(`${label}_path_invalid`, path);
  if (segments.includes(".git")) fail(`${label}_path_forbidden`, path);
}

function treeDigest(entries: TreeEntry[]): string {
  const sorted = [...entries].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const lines = sorted.map(
    (entry) =>
      `${entry.path}\0${entry.mode}\0${entry.blob}\0${entry.sha256}\0${entry.size}\0`,
  );
  return sha256Hex(lines.join(""));
}

function validateEntry(raw: unknown): TreeEntry {
  if (!raw || typeof raw !== "object" || Array.isArray(raw))
    fail("manifest_entry_invalid");
  const entry = raw as Record<string, unknown>;
  if (typeof entry.path !== "string") fail("manifest_entry_invalid");
  assertSafePath(entry.path, "manifest");
  if (entry.mode !== "100644" && entry.mode !== "100755")
    fail("manifest_entry_mode", entry.path);
  if (typeof entry.blob !== "string" || !/^[0-9a-f]{40}$/.test(entry.blob))
    fail("manifest_entry_blob", entry.path);
  if (typeof entry.sha256 !== "string" || !/^[0-9a-f]{64}$/.test(entry.sha256))
    fail("manifest_entry_sha256", entry.path);
  if (!Number.isInteger(entry.size) || (entry.size as number) < 0)
    fail("manifest_entry_size", entry.path);
  return {
    path: entry.path,
    mode: entry.mode,
    blob: entry.blob,
    sha256: entry.sha256,
    size: entry.size as number,
  };
}

function readManifest(path: string): Manifest {
  let text: string;
  try {
    text = readFileSync(path, "utf8");
  } catch {
    fail("manifest_unreadable");
  }
  let raw: Record<string, unknown>;
  try {
    const parsed = JSON.parse(text);
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed))
      fail("manifest_invalid");
    raw = parsed as Record<string, unknown>;
  } catch (error) {
    if (error instanceof FixtureError) throw error;
    fail("manifest_invalid_json");
  }
  if (raw.version !== 1) fail("manifest_version");
  if (typeof raw.commit !== "string" || !/^[0-9a-f]{40}$/.test(raw.commit))
    fail("manifest_commit");
  if (
    raw.parent !== undefined &&
    raw.parent !== null &&
    (typeof raw.parent !== "string" || !/^[0-9a-f]{40}$/.test(raw.parent))
  )
    fail("manifest_parent");
  if (!Array.isArray(raw.entries)) fail("manifest_entries");
  if (!Array.isArray(raw.parentEntries)) fail("manifest_parent_entries");
  const entries = raw.entries.map(validateEntry);
  const parentEntries = raw.parentEntries.map(validateEntry);
  if (entries.length > MAX_FILES || parentEntries.length > MAX_FILES)
    fail("manifest_too_many_files");
  if (new Set(entries.map((entry) => entry.path)).size !== entries.length)
    fail("manifest_duplicate_path");
  if (new Set(parentEntries.map((entry) => entry.path)).size !== parentEntries.length)
    fail("manifest_duplicate_parent_path");
  const total = entries.reduce((sum, entry) => sum + entry.size, 0);
  if (total > MAX_TOTAL_BYTES) fail("manifest_too_large");
  for (const entry of entries)
    if (entry.size > MAX_FILE_BYTES) fail("manifest_file_too_large", entry.path);
  if (typeof raw.treeSha256 !== "string" || raw.treeSha256 !== treeDigest(entries))
    fail("manifest_digest");
  return {
    version: 1,
    commit: raw.commit,
    parent: typeof raw.parent === "string" ? raw.parent : null,
    entries,
    parentEntries,
    treeSha256: raw.treeSha256 as string,
  };
}

function listSubjectFiles(root: string): string[] {
  const rootInfo = (() => {
    try {
      return lstatSync(root);
    } catch {
      fail("subject_unreadable");
    }
  })();
  if (!rootInfo.isDirectory() || rootInfo.isSymbolicLink())
    fail("subject_root_invalid");

  const files: string[] = [];
  const stack: Array<{ path: string; depth: number }> = [{ path: root, depth: 0 }];
  while (stack.length) {
    const current = stack.pop()!;
    if (current.depth > MAX_DEPTH) fail("subject_too_deep");
    let entries: string[];
    try {
      entries = readdirSync(current.path);
    } catch {
      fail("subject_unreadable");
    }
    for (const name of entries) {
      const full = join(current.path, name);
      let info;
      try {
        info = lstatSync(full);
      } catch {
        fail("subject_unreadable");
      }
      if (info.isSymbolicLink()) fail("subject_symlink", relative(root, full));
      if (info.isDirectory()) {
        stack.push({ path: full, depth: current.depth + 1 });
        continue;
      }
      if (!info.isFile()) fail("subject_special_file", relative(root, full));
      files.push(relative(root, full).split(sep).join("/"));
      if (files.length > MAX_FILES * 2) fail("subject_too_many_files");
    }
  }
  files.sort();
  return files;
}

const FORBIDDEN_BASENAMES = new Set([
  ".env",
  ".netrc",
  "owner-token",
  "credentials.json",
  "id_rsa",
  "id_ed25519",
  "e2e-preview-marker.txt",
  ".preview.log",
]);

function assertForbiddenPathsAbsent(paths: string[]): void {
  for (const path of paths) {
    const name = basename(path);
    const segments = path.split("/");
    if (segments.includes("node_modules")) fail("forbidden_path", path);
    if (FORBIDDEN_BASENAMES.has(name) || name.endsWith(".pem"))
      fail("forbidden_path", path);
  }
}

function checkText(path: string, content: Buffer): void {
  if (content.length > MAX_TEXT_BYTES) return;
  if (content.includes(0)) return;
  const text = content.toString("utf8");
  const lines = text.split("\n");
  for (const line of lines) {
    if (/[ \t]+$/.test(line)) fail("whitespace", path);
    const indent = /^[ \t]*/.exec(line)?.[0] ?? "";
    if (indent.includes(" \t")) fail("whitespace", path);
    if (/^(<<<<<<<|=======|>>>>>>>)(?: |$)/.test(line))
      fail("conflict_marker", path);
  }
  if (text.endsWith("\n\n")) fail("whitespace", path);
}

function verifySubject(root: string, manifest: Manifest): {
  files: number;
  bytes: number;
} {
  const actual = listSubjectFiles(root);
  assertForbiddenPathsAbsent(actual);
  const expected = new Map(manifest.entries.map((entry) => [entry.path, entry]));
  let bytes = 0;
  for (const path of actual) {
    const entry = expected.get(path);
    if (!entry) fail("subject_extra_file", path);
    const full = join(root, ...path.split("/"));
    let info;
    try {
      info = lstatSync(full);
    } catch {
      fail("subject_unreadable", path);
    }
    if (!info.isFile() || info.isSymbolicLink()) fail("subject_file_invalid", path);
    if (info.size !== entry.size) fail("subject_size_mismatch", path);
    if (info.size > MAX_FILE_BYTES) fail("subject_file_too_large", path);
    const content = readFileSync(full);
    if (content.length !== entry.size) fail("subject_size_mismatch", path);
    if (sha256Hex(content) !== entry.sha256) fail("subject_sha256_mismatch", path);
    if (gitBlobId(content) !== entry.blob) fail("subject_blob_mismatch", path);
    const executable = (info.mode & 0o111) !== 0;
    if (executable !== (entry.mode === "100755"))
      fail("subject_mode_mismatch", path);
    bytes += content.length;
    if (bytes > MAX_TOTAL_BYTES) fail("subject_too_large");
    checkText(path, content);
    expected.delete(path);
  }
  if (expected.size) fail("subject_missing_file", [...expected.keys()].sort()[0]);
  return { files: actual.length, bytes };
}

function verifyDelivery(root: string): void {
  const entry = join(root, "src", "e2e.ts");
  let source: string;
  try {
    source = readFileSync(entry, "utf8");
  } catch {
    fail("delivery_missing");
  }
  try {
    new Bun.Transpiler({ loader: "ts" }).transformSync(source);
  } catch {
    fail("delivery_syntax_invalid");
  }
  if (!/\bexport\s/.test(source)) fail("delivery_export_missing");
}

function reviewReport(manifest: Manifest): NonNullable<Report["review"]> {
  const parent = new Map(
    (manifest.parentEntries ?? []).map((entry) => [entry.path, entry]),
  );
  const changedFiles: NonNullable<Report["review"]>["changedFiles"] = [];
  for (const entry of manifest.entries) {
    const before = parent.get(entry.path);
    if (!before) changedFiles.push({ path: entry.path, status: "added", size: entry.size });
    else {
      if (before.blob !== entry.blob)
        changedFiles.push({ path: entry.path, status: "modified", size: entry.size });
      parent.delete(entry.path);
    }
  }
  for (const [path, entry] of parent)
    changedFiles.push({ path, status: "removed", size: entry.size });
  if (changedFiles.length > MAX_FILES) fail("review_too_many_changes");
  changedFiles.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return {
    changedFiles,
    added: changedFiles.filter((file) => file.status === "added").length,
    modified: changedFiles.filter((file) => file.status === "modified").length,
    removed: changedFiles.filter((file) => file.status === "removed").length,
  };
}

function run(): Report {
  const [modeArg, subject, manifestPath, challengeArg] = process.argv.slice(2);
  if (modeArg !== "ci" && modeArg !== "review")
    fail("mode_invalid");
  if (!subject || !manifestPath) fail("arguments_missing");
  if (!challengeArg || !/^[0-9a-f]{32,64}$/.test(challengeArg))
    fail("challenge_invalid");
  const mode: CiMode = modeArg;
  const challenge = challengeArg;
  const manifest = readManifest(manifestPath);
  const { files, bytes } = verifySubject(subject, manifest);
  verifyDelivery(subject);
  const report: Report = {
    version: 1,
    mode,
    challenge,
    commit: manifest.commit,
    treeSha256: manifest.treeSha256,
    files,
    bytes,
    checks: {
      manifestMatched: true,
      fileModesMatched: true,
      srcEntryPresent: true,
      typescriptSyntaxValid: true,
      deliveryExportPresent: true,
      whitespaceClean: true,
      conflictMarkersAbsent: true,
      forbiddenPathsAbsent: true,
      previewArtifactsAbsent: true,
    },
  };
  if (mode === "review") report.review = reviewReport(manifest);
  return report;
}

try {
  const report = run();
  process.stdout.write(JSON.stringify(report) + "\n");
} catch (error) {
  if (error instanceof FixtureError) {
    process.stderr.write(
      `E2E_CI_ERROR ${error.code}${error.detail ? ` ${safeDetail(error.detail)}` : ""}\n`,
    );
  } else {
    process.stderr.write("E2E_CI_ERROR fixture_failed\n");
  }
  process.exitCode = 1;
}
